"""
Aggregate cross-validation results across folds and random seeds.

This script collects and merges the per-seed outputs generated by
train_kfold_multiseed.py, producing consolidated datasets of model
performance metrics and sample-level predictions.

Main features:
    - Merge fold-level metrics across all completed seeds
    - Merge sample-level predictions across all completed seeds
    - Verify experiment completeness (seeds and folds)
    - Compute descriptive statistics across runs
    - Generate per-seed and global performance summaries
    - Support multiple experimental configurations through tagged outputs

Metrics summarized:
    Classification:
        TSS, HSS2, AUC, confusion-matrix statistics

    Regression (Poisson mode):
        MAE, MSE, RMSE, Bias, Pearson correlation,
        Poisson deviance, and outlier statistics

Outputs:
    results/kfold_all_seeds_metrics_<tag>.csv
        Combined metrics from all folds and seeds.

    results/kfold_all_seeds_predictions_<tag>.csv
        Combined sample-level predictions from all folds and seeds.

This script represents the final aggregation stage of the forecasting
pipeline and provides the performance statistics reported for each
experimental configuration.
"""

import argparse
import pandas as pd
import numpy as np
from pathlib import Path

CLASS_NAMES = ['C', 'M', 'X']
SPLITS      = ['train', 'val', 'pseudotest', 'test']

# Metrics logged for both modes
CLF_METRICS = ['TSS', 'HSS2', 'AUC', 'TP', 'FP', 'FN', 'TN', 'TPR', 'TNR']

# Additional metrics for Poisson regression only
REG_METRICS = ['MAE', 'MSE', 'RMSE', 'Bias',
               'PearsonR', 'PoissonDeviance', 'FracOutliers2x']

RESULTS_DIR = Path('results')


# ─────────────────────────────────────────────────────────────────────────────
# LOAD & MERGE
# ─────────────────────────────────────────────────────────────────────────────

def load_csvs(pattern: str) -> pd.DataFrame:
    files = sorted(RESULTS_DIR.glob(pattern))
    if not files:
        raise FileNotFoundError(
            f"No files found in {RESULTS_DIR} matching '{pattern}'")
    print(f"\nFound {len(files)} file(s) matching '{pattern}':")
    for f in files:
        print(f"  {f.name}")
    return pd.concat([pd.read_csv(f) for f in files], ignore_index=True)


# ─────────────────────────────────────────────────────────────────────────────
# SUMMARY TABLES
# ─────────────────────────────────────────────────────────────────────────────

def print_summary(df: pd.DataFrame, mode: str, split: str = 'test'):
    sub    = df[df['mode'] == mode]
    n_runs = len(sub)
    n_seeds = sub['seed'].nunique()
    n_folds = sub['fold'].nunique()

    metrics = CLF_METRICS + (REG_METRICS if mode == 'poisson' else [])

    print(f"\n{'='*72}")
    print(f"  {mode.upper()}  |  split={split}  |  "
          f"{n_seeds} seeds × {n_folds} folds = {n_runs} runs")
    print(f"{'='*72}")
    print(f"  {'Metric':<35}  {'Mean':>8}  {'Std':>8}  {'Min':>8}  {'Max':>8}")
    print(f"  {'-'*35}  {'-'*8}  {'-'*8}  {'-'*8}  {'-'*8}")

    for cls in CLASS_NAMES:
        first_in_class = True
        for metric in metrics:
            col = f'{split}_{metric}_{cls}'
            if col not in sub.columns:
                continue
            vals = sub[col].dropna()
            if len(vals) == 0:
                continue
            if first_in_class:
                print(f"  ── {cls}-class {'─'*55}")
                first_in_class = False
            print(f"  {col:<35}  {vals.mean():>8.4f}  {vals.std():>8.4f}"
                  f"  {vals.min():>8.4f}  {vals.max():>8.4f}")
    print(f"{'='*72}")


def per_seed_summary(df: pd.DataFrame, mode: str, split: str = 'test'):
    sub = df[df['mode'] == mode]
    metrics = CLF_METRICS + (REG_METRICS if mode == 'poisson' else [])
    cols = [f'{split}_{m}_{c}' for m in metrics for c in CLASS_NAMES
            if f'{split}_{m}_{c}' in sub.columns]
    # Keep only the most diagnostic subset for readability
    key_cols = [c for c in cols if any(
        m in c for m in ['TSS', 'AUC', 'MAE', 'PoissonDeviance', 'PearsonR'])]
    if not key_cols:
        key_cols = cols

    print(f"\n  ── Per-seed fold-mean ({mode.upper()}, split={split}) ──")
    seed_means = sub.groupby('seed')[key_cols].mean()
    print(seed_means.to_string(float_format='{:.4f}'.format))


def check_completeness(df: pd.DataFrame, expected_seeds: list,
                       expected_folds: list, mode: str):
    sub = df[df['mode'] == mode]
    for seed in expected_seeds:
        s = sub[sub['seed'] == seed]
        missing = set(expected_folds) - set(s['fold'].unique())
        if missing:
            print(f"  WARNING [{mode}] seed={seed}: missing folds {sorted(missing)}")


# ─────────────────────────────────────────────────────────────────────────────
# MAIN
# ─────────────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--tag',     default='*',
                        help='Feature tag to filter, e.g. "feat-tot_us_flux+tot_flux".'
                             ' Default: merge all tags.')
    parser.add_argument('--out',     default=None,
                        help='Output CSV for merged metrics '
                             '(default: SEED_RESULTS/kfold_all_seeds_metrics_<tag>.csv)')
    parser.add_argument('--split',   default='test', choices=SPLITS,
                        help='Split shown in the main printed summary')
    parser.add_argument('--no-preds', action='store_true',
                        help='Skip merging prediction CSVs')
    args = parser.parse_args()

    # ── Metrics ───────────────────────────────────────────────────────────
    metrics_pattern = f'metrics_{args.tag}_seed_*.csv'
    df = load_csvs(metrics_pattern)

    print(f"\nSeeds found : {sorted(df['seed'].unique())}")
    print(f"Folds found : {sorted(df['fold'].unique())}")
    print(f"Modes found : {sorted(df['mode'].unique())}")
    print(f"Total rows  : {len(df)}")

    expected_seeds = sorted(df['seed'].unique())
    expected_folds = sorted(df['fold'].unique())
    for mode in df['mode'].unique():
        check_completeness(df, expected_seeds, expected_folds, mode)

    tag_part = args.tag if args.tag != '*' else 'all'
    out_metrics = args.out or str(
        RESULTS_DIR / f'kfold_all_seeds_metrics_{tag_part}.csv')
    df.to_csv(out_metrics, index=False)
    print(f"\nMerged metrics CSV → {out_metrics}")

    # ── Main summary (test split) ─────────────────────────────────────────
    for mode in sorted(df['mode'].unique()):
        print_summary(df, mode, split=args.split)
        per_seed_summary(df, mode, split=args.split)

    # ── Full summary (all splits) ─────────────────────────────────────────
    print("\n\n── Full summary across all splits ──")
    for mode in sorted(df['mode'].unique()):
        for split in SPLITS:
            has_col = any(f'{split}_TSS_{c}' in df.columns for c in CLASS_NAMES)
            if has_col:
                print_summary(df, mode, split=split)

    # ── Predictions ───────────────────────────────────────────────────────
    if not args.no_preds:
        preds_pattern = f'predictions_{args.tag}_seed_*.csv'
        try:
            df_preds = load_csvs(preds_pattern)
            out_preds = str(
                RESULTS_DIR / f'kfold_all_seeds_predictions_{tag_part}.csv')
            df_preds.to_csv(out_preds, index=False)
            print(f"\nMerged predictions CSV → {out_preds}")
            print(f"Total prediction rows  : {len(df_preds)}")
            print(df_preds.groupby(['mode', 'split'])['seed']
                          .count().rename('n_samples').to_string())
        except FileNotFoundError as e:
            print(f"\n(Skipped predictions merge: {e})")


if __name__ == '__main__':
    main()